export default {
  name: 'PixelIcon',
  props: {
    name: {
      type: String,
      required: true
    },
    size: {
      type: [Number, String],
      default: 16
    }
  },
  computed: {
    runs() {
      const rows = ICON_MAPS[this.name] || []
      const runs = []
      rows.forEach((rawRow, y) => {
        const row = String(rawRow).padEnd(16, '.').slice(0, 16)
        let x = 0
        while (x < 16) {
          const tone = row.charAt(x)
          if (tone === '.') {
            x += 1
            continue
          }
          let width = 1
          while (x + width < 16 && row.charAt(x + width) === tone) {
            width += 1
          }
          runs.push({ x, y, w: width, tone })
          x += width
        }
      })
      return runs
    }
  }
