async function updateNovel645() {
	const connection = mysql.createConnection({ ...config.database, multipleStatements: true });
	const q = (sql, v = []) => new Promise((res, rej) => connection.query(sql, v, (e, r) => (e ? rej(e) : res(r))));

	try {
		await new Promise((resolve, reject) => connection.connect((e) => (e ? reject(e) : resolve())));

		const novel = await q('SELECT novel_id, deleted FROM novels WHERE novel_id = 645');
		if (!novel.length || novel[0].deleted) {
			throw new Error('novel 645 not found or deleted');
		}
		const existing = await q('SELECT COUNT(*) AS n FROM articles WHERE novel_id = 645 AND deleted = 0');
		if (existing[0].n > 0) {
			throw new Error(`novel 645 already has ${existing[0].n} articles, aborting to avoid duplicates`);
		}

		await connection.beginTransaction();
		try {
			for (let i = 0; i < chapters.length; i++) {
				const chapter = chapters[i];
				const content = JSON.stringify(
					chapter.paragraphs.map((value, index) => ({ type: 'text', value, id: index + 1 })),
				);
				const hash = crypto.createHash('md5').update(content).digest('hex');
				await q(
					'INSERT INTO articles(title, content, content_hash, novel_id, article_chapter, article_type, is_draft) VALUES(?,?,?,?,?,?,0)',
					[chapter.title, content, hash, 645, i + 1, 'richtext'],
				);
				console.log(`inserted: 第${i + 1}章 ${chapter.title}`);
			}
			await connection.commit();
			console.log('小说 645 参赛指南章节写入完成');
		} catch (e) {
			await connection.rollback();
			throw e;
		}
	} finally {
		connection.end();
	}
}

updateNovel645().catch((e) => {
	console.error('FAIL:', e.message);
	process.exitCode = 1;
});
