const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const babel = require('@babel/core');
const Vue = require('vue');
const compiled = file => babel.transformSync(fs.readFileSync(file, 'utf8'), { configFile:false, babelrc:false, plugins:[require('@babel/plugin-transform-modules-commonjs')] }).code;
const utils = {};
vm.runInNewContext(compiled('utils/site-theme.js'), { exports:utils });
const rows = new Map([['loghome.social.theme', 'dark']]);
const storage = { getItem:key=>rows.get(key)||null, setItem:(key,value)=>rows.set(key,value) };
assert.equal(utils.readThemePreference(storage), 'dark');
rows.set('loghome.theme','light');
assert.equal(utils.readThemePreference(storage), 'light');
assert.equal(utils.readThemePreference({getItem(){throw Error('denied')}}), 'system');
assert.equal(utils.saveThemePreference({setItem(){throw Error('denied')}}, 'dark'), 'dark');

function plugin(environment={}) {
  const exports={};
  vm.runInNewContext(compiled('plugins/site-theme.js'), { exports, ...environment, require:source=>source==='vue'?Vue:utils });
  let api; exports.default({}, (name,value)=>{assert.equal(name,'theme');api=value});
  return api;
}
const first=plugin(),second=plugin();
first.set('dark');
assert.equal(first.resolved,'dark');
assert.equal(second.resolved,'light');
const attributes=new Map(),events={},mediaEvents={};
const media={matches:true,addEventListener:(name,fn)=>mediaEvents[name]=fn};
const browser={localStorage:storage,matchMedia:()=>media,addEventListener:(name,fn)=>events[name]=fn};
const document={documentElement:{setAttribute:(key,value)=>attributes.set(key,value)}};
const site=plugin({window:browser,document});
assert.equal(site.resolved,'light');
const observer=new Vue({computed:{resolved(){return site.resolved}}});
site.toggle();
assert.equal(observer.resolved,'dark');
assert.equal(rows.get('loghome.theme'),'dark');
assert.equal(attributes.get('data-site-theme'),'dark');
site.set('system');
mediaEvents.change({matches:false});
assert.equal(site.resolved,'light');
rows.set('loghome.theme','dark');events.storage({key:'loghome.theme'});
assert.equal(site.resolved,'dark');
const denied={matchMedia:()=>media,addEventListener(){}};
Object.defineProperty(denied,'localStorage',{get(){throw Error('denied')}});
const privateBrowser=plugin({window:denied,document});
privateBrowser.set('light');
assert.equal(privateBrowser.resolved,'light');
observer.$destroy();
console.log('PASS site theme migration, persistence, reactive state, system/cross-tab changes, denied storage and SSR request isolation');
